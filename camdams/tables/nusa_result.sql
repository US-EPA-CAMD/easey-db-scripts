CREATE TABLE IF NOT EXISTS camdams.nusa_result
(
    nusa_result_id bigint GENERATED BY DEFAULT AS IDENTITY,
    nusa_result_date timestamp without time zone NOT NULL,
    prg_vintage_id numeric(38,0) NOT NULL,
    nusa_round numeric(1,0) NOT NULL,
    final_ind numeric(1,0) NOT NULL,
    state varchar(2) NOT NULL,
    indian_country_ind numeric(1,0) NOT NULL,
    multiplier numeric(15,6),
    authority_amount numeric(15,0) NOT NULL,
    sum_calculated_maximum numeric(15,0),
    sum_initial_adjusted numeric(15,0),
    sum_secondary_adjusted numeric(15,0),
    export_date timestamp without time zone,
    userid varchar(160) NOT NULL,
    PRIMARY KEY (nusa_result_id)
);
COMMENT ON TABLE camdams.nusa_result
    IS 'Table of results for the NUSA program.';
COMMENT ON COLUMN camdams.nusa_result.nusa_result_id
    IS 'Identity key for NUSA_RESULT table.';
COMMENT ON COLUMN camdams.nusa_result.nusa_result_date
    IS 'The most recent date the NUSA results were generated.';
COMMENT ON COLUMN camdams.nusa_result.prg_vintage_id
    IS 'Identity key for program vintage table.';
COMMENT ON COLUMN camdams.nusa_result.nusa_round
    IS 'The number of the NUSA round, either 1 or 2.';
COMMENT ON COLUMN camdams.nusa_result.final_ind
    IS 'Indicates if the result is final.';
COMMENT ON COLUMN camdams.nusa_result.state
    IS 'State abbreviation for state in which FACILITY, CONTACT, AGENCY, ACCOUNT REQUEST, PROGRAM, or STAFF is located.';
COMMENT ON COLUMN camdams.nusa_result.indian_country_ind
    IS 'Indicates whether or not a program may have units located in Indian Country.';
COMMENT ON COLUMN camdams.nusa_result.multiplier
    IS 'The maximum available NUSA authority for the state for the selected program and year divided by the sum of the Maximum Allocation values for the state for the selected program and year.';
COMMENT ON COLUMN camdams.nusa_result.authority_amount
    IS 'Total number of allowances the account can allocate for the specific year.';
COMMENT ON COLUMN camdams.nusa_result.sum_calculated_maximum
    IS 'Sum of maximum allocations that will be made to the units based on the total emissions that are subject to compliance (prior year emissions for first round or current year emissions for second round).';
COMMENT ON COLUMN camdams.nusa_result.sum_initial_adjusted
    IS 'Sum of initial adjusted allocation values for the units.';
COMMENT ON COLUMN camdams.nusa_result.sum_secondary_adjusted
    IS 'Sum of secondary adjusted allocation values for the units.';
COMMENT ON COLUMN camdams.nusa_result.export_date
    IS 'The most recent date the NUSA results were exported.';
COMMENT ON COLUMN camdams.nusa_result.userid
    IS 'The user name of the person or process that created the record if the Update Date is empty.  Otherwise this is the user name of the person or process that made the last update.';